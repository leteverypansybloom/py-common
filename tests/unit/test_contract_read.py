def _book(rows: list[list[Any]], title: str = "Events") -> bytes:
    """Build a one-sheet workbook.

    Args:
        rows: The rows, headings first.
        title: The sheet's name.

    Returns:
        The .xlsx bytes.
    """
    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = title
    for row in rows:
        ws.append(row)
    buffer = BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


def _contract(**kwargs: Any) -> Contract:
    """Build a contract for an Events sheet of name and count.

    Args:
        **kwargs: Extra Worksheet settings, such as on_mismatch.

    Returns:
        The contract.
    """
    return Contract(
        worksheets=[
            Worksheet(
                "Events",
                columns=[
                    Column("name", "string"),
                    Column("count", "integer", nullable=True),
                ],
                **kwargs,
            )
        ]
    )


class TestReadOnce:
    """read() returns what extract() does, after validating, in one go."""

    def test_read_returns_selected_rows(self) -> None:
        """read() returns the non-empty rows, with their row numbers."""
        data = _book([["name", "count"], ["a", 1], [None, None], ["b", 2]])

        sheets = _contract().read(data, "f.xlsx")

        assert sheets == {
            "Events": SheetRows(
                ["name", "count"], [(2, ("a", 1)), (4, ("b", 2))]
            )
        }
        assert sheets == _contract().extract(data)

    def test_workbook_is_opened_once_read_only(self) -> None:
        """The workbook is parsed once, not once per check."""
        data = _book([["name", "count"], ["a", 1]])
        real = openpyxl.load_workbook

        with patch(
            "py_common.contract.load_workbook", side_effect=real
        ) as opened:
            _contract().read(data, "f.xlsx")

        opened.assert_called_once()
        assert opened.call_args.kwargs["read_only"] is True

    def test_read_raises_what_validate_raises(self) -> None:
        """read() rejects what validate() rejects."""
        data = _book([["name", "count"], ["a", "x"]])

        with pytest.raises(ValidationError, match="expected integer"):
            _contract().read(data, "f.xlsx")

    def test_validate_and_extract_are_thin_wrappers(self) -> None:
        """validate() and extract() give the same answers as read()."""
        data = _book([["name", "count"], ["a", 1], ["b", 2]])

        assert _contract().validate(data, "f.xlsx") == 2

    def test_data_under_a_blank_heading_beyond_the_last_heading(self) -> None:
        """Read-only rows stop at their last cell; headings are padded."""
        contract = Contract(
            worksheets=[
                Worksheet(
                    "Events",
                    columns=[Column("name", "string")],
                    column_selection="all_except",
                )
            ]
        )
        data = _book([["name"], ["a", "extra"]])

        sheet = contract.read(data, "f.xlsx")["Events"]

        assert sheet.columns == ["name", "col_B"]
        assert sheet.rows == [(2, ("a", "extra"))]


class TestFormulasWithoutValues:
    """A formula with no stored result is not silently empty."""

    @pytest.fixture
    def data(self) -> bytes:
        """Return a workbook with one formula that has no saved value.

        Returns:
            The .xlsx bytes.
        """
        # openpyxl writes formulas without cached results, exactly as
        # files generated by code arrive.
        return _book([["name", "count"], ["a", "=1+1"], ["b", 3]])

    def test_scan_finds_the_cell(self, data: bytes) -> None:
        """The scan reports the formula's row and cell.

        Args:
            data: The workbook.
        """
        assert formulas_without_values(data, ["Events"]) == {
            "Events": [(2, "B2")]
        }

    def test_quarantine_mode_rejects_the_file(self, data: bytes) -> None:
        """A strict sheet rejects the file, naming the cell.

        Args:
            data: The workbook.
        """
        with pytest.raises(ValidationError, match="no saved value.*B2"):
            _contract().read(data, "f.xlsx")

    def test_warn_mode_warns_and_loads(self, data: bytes) -> None:
        """A "warn" sheet loads the cell as empty and says so.

        Args:
            data: The workbook.
        """
        warnings: list[str] = []

        sheets = _contract(on_mismatch="warn").read(data, "f.xlsx", warnings)

        assert any(
            "formula cell(s) have no saved value" in w for w in warnings
        )
        assert sheets["Events"].rows[0] == (2, ("a", None))

    def test_formulas_above_the_heading_row_are_ignored(self) -> None:
        """Formulas above the headings aren't data, so they're allowed."""
        data = _book([["=TODAY()"], ["name", "count"], ["a", 1]])

        assert _contract(header_row=2).read(data, "f.xlsx")

    def test_extract_does_not_check(self, data: bytes) -> None:
        """extract() reads the cell as empty without raising.

        Args:
            data: The workbook.
        """
        assert _contract().extract(data)["Events"].rows[0] == (2, ("a", None))


class TestWhitespaceIsEmpty:
    """Whitespace-only text doesn't satisfy a required column."""

    def test_whitespace_only_required_value_is_missing(self) -> None:
        """Spaces alone in a required column count as missing."""
        data = _book([["name", "count"], ["   ", 1]])

        with pytest.raises(ValidationError, match="'name' is required"):
            _contract().read(data, "f.xlsx")

    def test_whitespace_in_nullable_number_column_is_not_a_type_error(
        self,
    ) -> None:
        """Spaces in an optional number column are empty, not text."""
        data = _book([["name", "count"], ["a", "  "]])

        assert _contract().validate(data, "f.xlsx") == 1


def test_pipeline_parses_each_workbook_once() -> None:
    """process() validates and converts from a single parse."""
    from unittest.mock import Mock

    from py_common.model import Outcome, SourceItem
    from py_common.pipeline import Pipeline

    source = Mock()
    source.download.return_value = _book([["name", "count"], ["a", 1]])
    store = Mock()
    store.get.return_value = None
    warehouse = Mock()
    warehouse.identity = "p.d.events"
    warehouse.load.return_value = True
    pipeline = Pipeline(
        source, store, warehouse, _contract()
    )  # type: ignore[arg-type]
    real = openpyxl.load_workbook

    with patch("py_common.contract.load_workbook", side_effect=real) as opened:
        result = pipeline.process(SourceItem("f.xlsx", "f.xlsx", "1", 1))

    assert result.outcome == Outcome.LOADED, result.errors
    opened.assert_called_once()


